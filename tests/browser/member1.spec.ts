import { test, expect } from '@playwright/test';

test('US01–08 integrated persistent workflow on production-built UI', async ({ page, request }) => {
  const suffix = Date.now();
  const name = `Browser Studio ${suffix}`;
  const renamed = `Renamed Studio ${suffix}`;
  const username = `designer.${suffix}`;
  await page.goto('/admin/profiles');
  await page.getByRole('button', { name: 'Create User Profile', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Profile Name').fill(name);
  await dialog.getByRole('combobox', { name: 'Role', exact: true }).selectOption('designer');
  await dialog.getByLabel('Manage projects', { exact: true }).check();
  await dialog.getByRole('button', { name: 'Create User Profile', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.locator('.toast')).toContainText('created successfully');
  await page.getByPlaceholder('Search profiles by name...').fill(name.toUpperCase());
  let row = page.getByRole('row').filter({ hasText: name });
  await expect(row).toHaveCount(1);
  await row.getByRole('button', { name: 'View', exact: true }).click();
  await expect(dialog).toContainText(name);
  await expect(dialog).toContainText('Manage projects');
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  await dialog.getByLabel('Profile Name').fill(renamed);
  await dialog.getByRole('button', { name: 'Save Changes' }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Clear search' }).click();
  await page.goto('/admin/accounts');
  await page.getByRole('button', { name: 'Create User Account', exact: true }).click();
  await dialog.getByRole('textbox', { name: 'Username', exact: true }).fill(username);
  await dialog.getByRole('textbox', { name: 'Email', exact: true }).fill(`${username}@example.test`);
  await dialog.getByLabel('Initial Password').fill('Browser test passphrase 42');
  await dialog.getByLabel('Assigned User Profile').selectOption({ label: renamed });
  await dialog.getByRole('button', { name: 'Create User Account', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.reload();
  row = page.getByRole('row').filter({ hasText: username });
  await expect(row).toContainText(renamed);
  await row.getByRole('button', { name: 'View', exact: true }).click();
  await expect(dialog).toContainText(username);
  await expect(dialog).not.toContainText('password');
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  await dialog.getByRole('textbox', { name: 'Email', exact: true }).fill(`updated.${suffix}@example.test`);
  await expect(dialog.getByLabel('Initial Password')).toHaveCount(0);
  await dialog.getByRole('button', { name: 'Save Changes' }).click();
  await expect(dialog).not.toBeVisible();
  await expect(row).toContainText(`updated.${suffix}@example.test`);
  await page.goto('/admin/profiles');
  row = page.getByRole('row').filter({ hasText: renamed });
  await row.getByRole('button', { name: 'Suspend', exact: true }).click();
  await expect(dialog).toContainText('account status remains unchanged');
  await dialog.getByRole('button', { name: 'Suspend User Profile', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(row).toContainText('Suspended');
  await page.reload();
  await expect(page.getByRole('row').filter({ hasText: renamed })).toContainText('Suspended');
  await page.goto('/admin/accounts');
  await expect(page.getByRole('row').filter({ hasText: username })).toContainText(`${renamed} (Suspended)`);
  await page.getByRole('button', { name: 'Create User Account', exact: true }).click();
  await expect(dialog.getByLabel('Assigned User Profile')).toBeVisible();
  await expect(dialog.getByRole('option', { name: renamed, exact: true })).toHaveCount(0);
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  await page.getByRole('row').filter({ hasText: username }).getByRole('button', { name: 'Edit', exact: true }).click();
  await expect(dialog.getByLabel('Assigned User Profile')).toContainText('current assignment only');
  await dialog.getByRole('textbox', { name: 'Email', exact: true }).fill(`retained.${suffix}@example.test`);
  await dialog.getByRole('button', { name: 'Save Changes' }).click();
  await expect(dialog).not.toBeVisible();
  const accounts = await (await request.get('/api/accounts')).json();
  const account = accounts.find((value: { username: string }) => value.username === username);
  expect(account.status).toBe('Active');
  const profile = await (await request.get(`/api/profiles/${account.profileId}`)).json();
  expect(profile.status).toBe('Suspended');
});

test('cancel actions never mutate persisted data, including suspension confirmation', async ({ page, request }) => {
  const response = await request.post('/api/profiles', { data: { name: `Cancel ${Date.now()}`, role: 'customer', permissions: ['projects:discover'] } });
  const profile = await response.json();
  await page.goto('/admin/profiles');
  let row = page.getByRole('row').filter({ hasText: profile.name });
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Profile Name').fill('Cancelled change');
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  expect(await (await request.get(`/api/profiles/${profile.profileId}`)).json()).toEqual(profile);
  await row.getByRole('button', { name: 'Suspend', exact: true }).click();
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  expect(await (await request.get(`/api/profiles/${profile.profileId}`)).json()).toEqual(profile);
  const before = await (await request.get('/api/profiles')).json();
  await page.getByRole('button', { name: 'Create User Profile', exact: true }).click();
  await dialog.getByLabel('Profile Name').fill('Cancelled creation');
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  expect(await (await request.get('/api/profiles')).json()).toEqual(before);
  await page.goto('/admin/accounts');
  const accounts = await (await request.get('/api/accounts')).json();
  await page.getByRole('button', { name: 'Create User Account', exact: true }).click();
  await dialog.getByRole('textbox', { name: 'Username', exact: true }).fill('cancelled.user');
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  row = page.getByRole('row').filter({ hasText: 'dev.admin@example.test' });
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  await dialog.getByRole('textbox', { name: 'Username', exact: true }).fill('cancelled.admin');
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  expect(await (await request.get('/api/accounts')).json()).toEqual(accounts);
});

test('failed save preserves form data and reports no success; submit lock prevents duplicate requests', async ({ page }) => {
  await page.goto('/admin/profiles');
  await page.getByRole('button', { name: 'Create User Profile', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Profile Name').fill('Will retry');
  await dialog.getByLabel('Discover projects', { exact: true }).check();
  let count = 0;
  let release: () => void = () => {};
  const gate = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/profiles', async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return; }
    count++; await gate;
    await route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: { code: 'PERSISTENCE', message: 'Storage unavailable. Retry saving.' } }) });
  });
  const submit = dialog.getByRole('button', { name: 'Create User Profile', exact: true });
  await submit.click();
  await expect(dialog.getByRole('button', { name: 'Saving…' })).toBeDisabled();
  await expect(dialog.getByRole('button', { name: 'Cancel' })).toBeDisabled();
  await page.keyboard.press('Escape');
  await expect(dialog).toBeVisible();
  await dialog.locator('form').evaluate(form => {
    form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
  });
  await expect.poll(() => count).toBe(1);
  release();
  await expect(dialog.getByRole('alert')).toContainText('Storage unavailable');
  await expect(dialog.getByLabel('Profile Name')).toHaveValue('Will retry');
  await expect(page.locator('.toast')).not.toHaveClass(/visible/);
  await expect(submit).toBeEnabled();
  await page.unroute('**/api/profiles');
  await submit.click();
  await expect(dialog).not.toBeVisible();
  await expect(page.locator('.toast')).toContainText('created successfully');
});

test('loading failures differ from empty results and details can retry', async ({ page }) => {
  await page.route('**/api/profiles?*', route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: { code: 'PERSISTENCE', message: 'List unavailable' } }) }));
  await page.goto('/admin/profiles');
  await expect(page.getByRole('alert')).toContainText('List unavailable');
  await expect(page.getByText('No matching profiles', { exact: true })).toHaveCount(0);
  await page.unroute('**/api/profiles?*');
  await page.getByRole('button', { name: 'Retry' }).click();
  await expect(page.getByRole('table')).toBeVisible();
  await page.getByPlaceholder('Search profiles by name...').fill('no such profile 987654321');
  await expect(page.getByText('No matching profiles', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Clear search' }).click();
  await page.route('**/api/profiles/dev-profile-admin', route => route.fulfill({ status: 404, contentType: 'application/json', body: JSON.stringify({ error: { code: 'NOT_FOUND', message: 'Profile was not found' } }) }));
  await page.getByRole('row').filter({ hasText: 'dev-profile-admin' }).getByRole('button', { name: 'View', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('alert')).toContainText('Profile was not found');
  await page.unroute('**/api/profiles/dev-profile-admin');
  await dialog.getByRole('button', { name: 'Retry' }).click();
  await expect(dialog).toContainText('User Admin');
});

test('account save rechecks profile status and retains entered values on failure', async ({ page, request }) => {
  const suffix = Date.now();
  const profile = await (await request.post('/api/profiles', { data: { name: `Stale assignment ${suffix}`, role: 'customer', permissions: ['projects:discover'] } })).json();
  await page.goto('/admin/accounts');
  await page.getByRole('button', { name: 'Create User Account', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('textbox', { name: 'Username', exact: true }).fill(`stale.${suffix}`);
  await dialog.getByRole('textbox', { name: 'Email', exact: true }).fill(`stale.${suffix}@example.test`);
  await dialog.getByLabel('Initial Password').fill('A long account passphrase');
  await dialog.getByLabel('Assigned User Profile').selectOption(profile.profileId);
  await request.post(`/api/profiles/${profile.profileId}/suspend`, { data: {} });
  await dialog.getByRole('button', { name: 'Create User Account', exact: true }).click();
  await expect(dialog.locator('#admin-profileId-error')).toContainText('active profile');
  await expect(dialog.getByRole('textbox', { name: 'Username', exact: true })).toHaveValue(`stale.${suffix}`);
  await expect(dialog.getByLabel('Initial Password')).toHaveValue('A long account passphrase');
  await expect(page.locator('.toast')).not.toHaveClass(/visible/);
  await dialog.getByLabel('Assigned User Profile').selectOption('dev-profile-customer');
  await dialog.getByRole('button', { name: 'Create User Account', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('row').filter({ hasText: `stale.${suffix}` })).toContainText('Customer');
});

